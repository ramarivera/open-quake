export type SpokenStatus = keyof typeof SPOKEN_STATUS.en;
export const spokenStatus = (locale: string, status: SpokenStatus): string => {
	const language = locale.toLowerCase().split(/[-_]/)[0];
	const selected =
		language && Object.hasOwn(SPOKEN_STATUS, language)
			? Object.entries(SPOKEN_STATUS).find(([key]) => key === language)?.[1]
			: undefined;
	return (selected ?? SPOKEN_STATUS.en)[status];
};
